"""Bounded deterministic synthetic fixtures and private local measurements."""
import hashlib
import io
import json
import os
from pathlib import Path
import platform
import sqlite3
import stat
import sys
import time
import tracemalloc
import zipfile

from recaplib.recovery import _reject_existing, _publish_new_file
from recaplib.strict_json import loads

MAX_BYTES = 64 * 1024 * 1024
MAX_PRODUCTS = 50000
FILES = ('web.json', 'local.jsonl', 'normalized.jsonl', 'web.zip')
BOUNDARY = ('Synthetic local observations only; no pass/fail threshold or speed guarantee. '
            'Timing and Python allocation tracing use separate runs. OS caches are not reset; '
            'Python tracemalloc excludes SQLite native allocations, OS caches and total process RSS. '
            'Inputs and generated bytes remain in memory; this is not a streaming benchmark. '
            'The private receipt includes interpreter, machine and timing observations. '
            'Failure can leave newly created scratch files; inspect them and retry with fresh paths. '
            'No existing archive is accepted. No network access or publication authorization.')


def _json(value):
    return (json.dumps(value, ensure_ascii=True, allow_nan=False, indent=2) + '\n').encode('ascii')


def _line(value):
    return (json.dumps(value, ensure_ascii=True) + '\n').encode('ascii')


def _hash(raw):
    return hashlib.sha256(raw).hexdigest()


def _parameters(n, m, seed):
    if (type(n) is not int or type(m) is not int or not 1 <= n <= 50000 or not 1 <= m <= 1000 or
            n*m > MAX_PRODUCTS or type(seed) is not int or not 0 <= seed <= 2**32-1):
        raise ValueError('fixture requires bounded integer counts and seed')


def _fixture(n, m, seed):
    _parameters(n,m,seed)
    web, local, normalized = [], [], []
    used = 0
    for i in range(n):
        conversation = 'synthetic-%06d' % i
        local.append(_line(dict(type='session_meta',payload=dict(id=conversation))))
        mapping = {}
        for j in range(m):
            identity = 'm%06d' % j
            token = _hash(('%d:%d:%d' % (seed,i,j)).encode())[:16]
            text = 'Synthetic orchard body %s %d %d' % (token,i,j)
            role = 'user' if j % 2 == 0 else 'assistant'
            mapping[identity] = dict(parent=None if j==0 else 'm%06d' % (j-1),
                message=dict(id=identity,author=dict(role=role),create_time=j+1,content=dict(parts=[text])))
            local.append(_line(dict(type='response_item',timestamp='2026-01-01T00:00:00Z',
                payload=dict(type='message',id=identity,role=role,content=[dict(type='input_text' if role=='user' else 'output_text',text=text)]))))
            normalized.append(_line(dict(conversation_id=conversation,message_id=identity,role=role,
                timestamp='2026-01-01T00:00:00Z',text=text,title='Synthetic orchard title')))
            used += len(local[-1])+len(normalized[-1])+len(_json(mapping[identity]))
            if used > MAX_BYTES//2:
                raise ValueError('synthetic fixture exceeds the byte bound')
        web.append(dict(id=conversation,title='Synthetic orchard title',mapping=mapping,current_node='m%06d' % (m-1)))
    data = dict(zip(FILES[:3],(_json(web),b''.join(local),b''.join(normalized))))
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer,'w',compression=zipfile.ZIP_STORED) as archive:
        entry=zipfile.ZipInfo('conversations.json',(2000,1,1,0,0,0))
        entry.create_system=3; entry.external_attr=0o100600 << 16
        archive.writestr(entry,data['web.json'])
    data['web.zip']=buffer.getvalue()
    if sum(map(len,data.values())) > MAX_BYTES:
        raise ValueError('synthetic fixture exceeds the byte bound')
    manifest=dict(schema='recap.synthetic-scale-fixture.v1',conversations=n,messages_per_conversation=m,seed=seed,
                  synthetic_only=True,files=[dict(path=name,bytes=len(data[name]),sha256=_hash(data[name])) for name in FILES])
    return data,manifest


def _parents(path):
    path=Path(os.path.abspath(path))
    for parent in path.parents:
        if parent.is_symlink() or not parent.is_dir():
            raise ValueError('existing nonsymlink parent directories required')
    return path


def _new(path):
    path=_parents(path)
    _reject_existing(path)
    return path


def _mkdir(path):
    path.mkdir(mode=0o700)


def _check_publication(result):
    if isinstance(result, dict) and result.get('staging_cleanup_complete') is False:
        raise ValueError('new synthetic files were published; staging cleanup incomplete; '
                         'inspect new scratch files before retrying')
    return result


def _summary(**values):
    return dict(values, synthetic_only=True, contains_message_text=False,
                existing_archive_access=False, network_access=False,
                boundary='Synthetic scratch work only, not a speed, completeness, rights or recovery guarantee. '
                         'Published files are not overwritten; inspect any reported staging remainder before retrying.')


def _check_result(name, result, expected_messages):
    _check_publication(result)
    if name.startswith('import_') and (result.get('records') != expected_messages or
                                      result.get('inserted') != expected_messages):
        raise ValueError('synthetic import did not produce the expected message counts')
    if name == 'rehearse_recovery' and result.get('status') != 'RECOVERY_REHEARSAL_PASSED':
        raise ValueError('synthetic recovery operation did not pass its functional checks')
    if name == 'check_import' and result.get('status') != 'NO_CONFLICTS':
        raise ValueError('synthetic import check reported conflicts')


def generate_fixture(output_dir, n=50, m=10, seed=0):
    output_dir=_new(output_dir)
    data,manifest=_fixture(n,m,seed)
    _mkdir(output_dir)
    for name,raw in data.items():
        _check_publication(_publish_new_file(output_dir/name,raw,'.recap-fixture-'))
    _check_publication(_publish_new_file(output_dir/'manifest.json',_json(manifest),'.recap-fixture-'))
    return _summary(status='GENERATED',conversations=n,messages=n*m,files=len(data)+1,staging_cleanup_complete=True)


def _read(path,limit):
    if path.is_symlink() or not stat.S_ISREG(path.stat().st_mode) or path.stat().st_size>limit:
        raise ValueError('fixture must contain bounded regular nonsymlink files')
    with path.open('rb') as stream:
        raw=stream.read(limit+1)
    if len(raw)>limit:
        raise ValueError('fixture file exceeds byte bound')
    return raw


def validate_fixture(directory):
    directory=_parents(directory)
    if directory.is_symlink() or not directory.is_dir():
        raise ValueError('fixture must be a nonsymlink directory')
    if {p.name for p in directory.iterdir()} != set(FILES)|{'manifest.json'}:
        raise ValueError('fixture has unexpected or missing entries')
    raw=_read(directory/'manifest.json',16384)
    try:
        manifest=loads(raw.decode('utf-8'))
        data,expected=_fixture(manifest['conversations'],manifest['messages_per_conversation'],manifest['seed'])
        if manifest != expected or raw != _json(expected):
            raise ValueError()
    except (ValueError,TypeError,KeyError,UnicodeError,RecursionError):
        raise ValueError('fixture manifest is not an exact deterministic synthetic declaration') from None
    for name,generated in data.items():
        if _read(directory/name,len(generated)) != generated:
            raise ValueError('fixture bytes do not match deterministic synthetic regeneration')
    return data,expected,_hash(raw)


def _code_identity():
    root=Path(__file__).resolve().parents[1]
    paths=sorted((root/'recaplib').glob('*.py'))+[root/'benchmark.py',root/'examples/make_scale_fixture.py']
    release=loads((root/'PUBLICATION_MANIFEST.json').read_text(encoding='utf-8'))['release']
    return dict(release=release,files={path.relative_to(root).as_posix():_hash(path.read_bytes()) for path in paths})


def run_benchmark(fixture_dir, work_dir, output, repetitions=1):
    work_dir=_new(work_dir); output=_new(output)
    if work_dir == output:
        raise ValueError('scratch directory and receipt must be distinct')
    if type(repetitions) is not int or not 1<=repetitions<=5:
        raise ValueError('repetitions must be an integer in 1..5')
    fixture_path=Path(fixture_dir).absolute()
    if output==fixture_path or fixture_path in output.parents or work_dir==fixture_path or fixture_path in work_dir.parents:
        raise ValueError('scratch and receipt must be outside fixture directory')
    if tracemalloc.is_tracing():
        raise ValueError('benchmark requires no preexisting allocation tracing session')
    data,manifest,fixture_hash=validate_fixture(fixture_dir)
    identity=_code_identity()
    _mkdir(work_dir)
    for name,raw in data.items():
        _check_publication(_publish_new_file(work_dir/name,raw,'.recap-input-'))
    from recaplib.archive import ingest, search, readonly
    from recaplib.session_workflow import import_export, titles
    from recaplib.conversation_search import find
    from recaplib.conversation_view import conversations, conversation
    from recaplib.title_batch import review_queue
    from recaplib.title_review_state import review_state
    from recaplib.title_history import history
    from recaplib.import_check import check_import
    from recaplib.export_inventory import list_export
    from recaplib.inspect_web_zip import inspect_web_zip
    from recaplib.prepare_web_export import prepare_web_export
    from recaplib.recovery import declare_recovery, rehearse_recovery
    db=work_dir/'read.sqlite'
    import_export(db,'synthetic',work_dir/'web.json','web')
    first='synthetic-000000'
    for index in range(0,manifest['conversations'],2):
        selected='synthetic-%06d' % index
        revision=0
        for step in range(3):
            revision=titles(db,'synthetic',selected,
                'Synthetic revised orchard title %d' % (step+1),revision)['revision']
        state=review_state(db,'synthetic',selected)
        review_state(db,'synthetic',selected,'skipped',state['state_revision'],
                     state['expected_title_revision'],state['expected_content_sha256'])
    connection=readonly(db)
    try:
        connection.execute('BEGIN')
        baseline=dict(archive_bytes=db.stat().st_size,
            messages=connection.execute('SELECT COUNT(*) FROM messages').fetchone()[0],
            conversations=connection.execute('SELECT COUNT(DISTINCT conversation_id) FROM messages').fetchone()[0],
            title_history=connection.execute('SELECT COUNT(*) FROM title_history').fetchone()[0],
            review_history=connection.execute('SELECT COUNT(*) FROM title_review_history').fetchone()[0])
    finally:
        connection.close()
    recovery=work_dir/'baseline-recovery.json'
    _check_publication(declare_recovery(db,recovery))
    before=_hash(db.read_bytes())
    counter=0
    def fresh(suffix):
        nonlocal counter
        counter+=1
        return work_dir/('measurement-%06d%s' % (counter,suffix))
    operations={
        'import_web':lambda:import_export(fresh('.sqlite'),'synthetic',work_dir/'web.json','web'),
        'import_local_codex':lambda:import_export(fresh('.sqlite'),'synthetic',work_dir/'local.jsonl','local-codex'),
        'import_normalized':lambda:ingest(fresh('.sqlite'),'synthetic',work_dir/'normalized.jsonl'),
        'find_title':lambda:find(db,'revised',source='synthetic'),
        'find_body':lambda:find(db,'body',source='synthetic'),
        'find_miss':lambda:find(db,'zzmissingfixturetoken',source='synthetic'),
        'fts_search':lambda:search(db,'orchard'),
        'list_offset':lambda:conversations(db,'synthetic',limit=20,offset=manifest['conversations']//2),
        'show':lambda:conversation(db,'synthetic',first,limit=20),
        'review_plain':lambda:review_queue(db,'synthetic'),
        'review_unrenamed':lambda:review_queue(db,'synthetic',unrenamed_only=True),
        'review_state':lambda:review_queue(db,'synthetic',review_state_filter='skipped'),
        'title_history':lambda:history(db,'synthetic',first),
        'check_import':lambda:check_import(db,'synthetic',work_dir/'web.json','web'),
        'list_export':lambda:list_export(work_dir/'web.json','web'),
        'inspect_zip':lambda:inspect_web_zip(work_dir/'web.zip'),
        'prepare_zip':lambda:prepare_web_export(work_dir/'web.zip','conversations.json',fresh('.json')),
        'declare_recovery':lambda:declare_recovery(db,fresh('.json')),
        'rehearse_recovery':lambda:rehearse_recovery(recovery,db,fresh('.json')),
    }
    measurements={}
    for name,operation in operations.items():
        elapsed=[];peaks=[]
        for _ in range(repetitions):
            start=time.perf_counter();result=operation();elapsed.append(time.perf_counter()-start)
            _check_result(name,result,manifest['conversations']*manifest['messages_per_conversation'])
        for _ in range(repetitions):
            tracemalloc.start()
            try:
                result=operation();peaks.append(tracemalloc.get_traced_memory()[1])
            finally:
                tracemalloc.stop()
            _check_result(name,result,manifest['conversations']*manifest['messages_per_conversation'])
        measurements[name]=dict(elapsed_seconds=elapsed,python_peak_bytes=peaks)
    if _hash(db.read_bytes()) != before or any((work_dir/name).read_bytes()!=raw for name,raw in data.items()):
        raise ValueError('benchmark baseline or synthetic input changed unexpectedly')
    validate_fixture(fixture_dir)
    receipt=dict(schema='recap.benchmark-receipt.v1',synthetic_only=True,network_access=False,
                 existing_archive_access=False,
                 functional_gates='Expected import record/insertion counts, no import conflicts, successful recovery rehearsal, and complete intermediate staging cleanup; gates run after measurement.',
                 fixture_manifest_sha256=fixture_hash,
                 fixture=dict(conversations=manifest['conversations'],messages_per_conversation=manifest['messages_per_conversation'],seed=manifest['seed']),
                 repetitions=repetitions,operations=measurements,code_identity=identity,baseline=baseline,
                 runtime=dict(python=sys.version,implementation=platform.python_implementation(),sqlite=sqlite3.sqlite_version,
                              system=platform.system()),
                 boundary=BOUNDARY)
    encoded=_json(receipt)
    if len(encoded)>MAX_BYTES:
        raise ValueError('benchmark receipt exceeds byte bound')
    publication=_publish_new_file(output,encoded,'.recap-benchmark-')
    return _summary(status='RECORDED',operations=len(operations),repetitions=repetitions,
                timing_runs=len(operations)*repetitions,traced_runs=len(operations)*repetitions,
                receipt_published=True, **publication)
